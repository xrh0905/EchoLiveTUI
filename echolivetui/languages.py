def language_label(code):
    if not code:
        return "自动检测（留空）"
    name, native = LANGUAGES.get(code, (code, code))
    return " · ".join(dict.fromkeys((name, native, code)))


def language_options(search="", *, automatic=False):
    codes = [*PINNED, *(code for code in sorted(LANGUAGES) if code not in PINNED)]
    query = search.strip().casefold()
    options = [(language_label(code), code) for code in codes if query in language_label(code).casefold()]
    return [(language_label(""), ""), *options] if automatic else options
